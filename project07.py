import os
import zipfile
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from google.colab import files

"""## 2. Upload and load dataset"""

up = files.upload()

# unzip uploaded zip files
for name in up:
    if name.endswith('.zip'):
        with zipfile.ZipFile(name) as z:
            z.extractall('data')

# find diabetic_data.csv
path = None
for folder, sub, fl in os.walk('.'):
    for f in fl:
        if f.startswith('diabetic_data') and f.endswith('.csv'):
            path = os.path.join(folder, f)

if path is None:
    print('Error: diabetic_data.csv not found. Run this cell again and upload the CSV or ZIP file.')
else:
    df = pd.read_csv(path)
    print('Loaded:', path)
    # ID columns hidden for privacy
    display(df.drop(columns=['encounter_id', 'patient_nbr']).head())

"""## 3. Dataset inspection"""

print(df.shape)
df.info()
display(df.describe())

"""## 4. Check missing values"""

# this dataset writes missing values as '?'
q = (df == '?').sum()
q = q[q > 0]
print(q)

# change '?' to NaN so isnull() can find them (no column is dropped)
df = df.replace('?', np.nan)

miss = df.isnull().sum()
miss = miss[miss > 0]
pct = (miss / len(df) * 100).round(1)
print(pct.sort_values(ascending=False))

"""## 5. Check duplicate records"""

print('Duplicate rows:', df.duplicated().sum())
print('Duplicate encounter_id:', df['encounter_id'].duplicated().sum())

# exact copies add no new information, so remove them
df = df.drop_duplicates()
print('Rows now:', len(df))

"""## 6. Validate patient_nbr and encounter_id"""

print(df[['encounter_id', 'patient_nbr']].isnull().sum())
print('encounter_id unique:', df['encounter_id'].is_unique)
print('Encounters:', len(df))
print('Unique patients:', df['patient_nbr'].nunique())

cnt = df['patient_nbr'].value_counts()
print('Patients with more than 1 encounter:', (cnt > 1).sum())

"""## 7. Data types and categorical columns"""

print(df.dtypes.value_counts())

cat = df.select_dtypes(exclude='number').columns
print(list(cat))

# numeric codes that are really categories
codes = ['admission_type_id', 'discharge_disposition_id', 'admission_source_id']
print(df[codes].nunique())

for c in ['gender', 'age', 'readmitted']:
    print(df[c].value_counts())

"""## 8. Average and median hospital stay"""

stay = df['time_in_hospital']
print('Mean:', round(stay.mean(), 2))
print('Median:', stay.median())
print('Min and max:', stay.min(), stay.max())

"""## 9. Length-of-stay quantiles (with NumPy)"""

print(stay.quantile([0.25, 0.5, 0.75, 0.9, 0.95]))

# NumPy operations
arr = np.array(df['time_in_hospital'])          # create array
print(arr[:10])                                  # slicing
print(arr.mean(), np.median(arr))                # mean, median
print(np.percentile(arr, [25, 50, 75, 90]))      # percentiles

long_arr = arr[arr >= 7]                         # boolean filtering
print('Stays of 7+ days (%):', round(len(long_arr) / len(arr) * 100, 1))

hours = arr * 24                                 # vectorised calculation
print('Mean stay in hours:', round(hours.mean(), 1))

df['stay_type'] = np.where(arr >= 7, 'long', 'short')

# NumPy bootstrap: uncertainty of the mean stay
np.random.seed(1)
means = []
for i in range(1000):
    s = np.random.choice(arr, size=len(arr), replace=True)
    means.append(s.mean())

print('95% range of mean stay:', np.percentile(means, [2.5, 97.5]).round(3))

"""## 10. Patient visit frequency"""

visits = df.groupby('patient_nbr').size()
print(visits.describe())
print(visits.value_counts().sort_index().head(10))
print('Patients with only 1 encounter (%):', round((visits == 1).mean() * 100, 1))

# add visit count to each row and make groups
df['visits'] = df['patient_nbr'].map(visits)
df['visit_grp'] = pd.cut(df['visits'], bins=[0, 1, 3, 1000],
                         labels=['1 visit', '2-3 visits', '4+ visits']).astype(str)
print(df['visit_grp'].value_counts())

"""## 11. Readmission categories"""

rd = df['readmitted'].value_counts()
print(rd)
print((rd / len(df) * 100).round(1))

# flags: 1 = yes, 0 = no
df['r30'] = (df['readmitted'] == '<30').astype(int)
df['any_re'] = (df['readmitted'] != 'NO').astype(int)

rd = rd.reindex(['<30', '>30', 'NO'])
plt.bar(rd.index, rd.values)
plt.title('Readmission Categories')
plt.xlabel('Readmitted')
plt.ylabel('Number of encounters')
plt.show()

"""## 12. Readmission and stay by age group"""

age_tab = pd.crosstab(df['age'], df['readmitted'], normalize='index') * 100
print(age_tab.round(1))

age_los = df.groupby('age')['time_in_hospital'].agg(['count', 'mean', 'median']).round(2)
print(age_los)

plt.figure(figsize=(9, 5))
plt.bar(age_los.index, age_los['mean'])
plt.title('Average Hospital Stay by Age Group')
plt.xlabel('Age group')
plt.ylabel('Average stay (days)')
plt.xticks(rotation=45)
plt.show()

"""## 13. Hospital stay by gender"""

# only Male and Female are compared (other value has very few rows)
d = df[df['gender'].isin(['Male', 'Female'])]
print('Rows left out:', len(df) - len(d))

g = d.groupby('gender')['time_in_hospital'].agg(['count', 'mean', 'median']).round(2)
print(g)

plt.bar(g.index, g['mean'])
plt.title('Average Hospital Stay by Gender')
plt.xlabel('Gender')
plt.ylabel('Average stay (days)')
plt.show()

"""## 14. Hospital stay by medical specialty"""

# specialty is missing for many rows, so only known values are used
sp = df[df['medical_specialty'].notnull()]

# keep the 10 most common specialties (small groups are unreliable)
top = sp['medical_specialty'].value_counts().head(10).index
sp = sp[sp['medical_specialty'].isin(top)]

s = sp.groupby('medical_specialty')['time_in_hospital'].agg(['count', 'mean']).round(2)
s = s.sort_values('mean')
print(s)

plt.figure(figsize=(9, 5))
plt.barh(s.index, s['mean'])
plt.title('Average Hospital Stay by Specialty (10 most common)')
plt.xlabel('Average stay (days)')
plt.ylabel('Medical specialty')
plt.tight_layout()
plt.show()

"""## 15. Pivot tables and cross-tabulations"""

p1 = pd.pivot_table(d, values='time_in_hospital', index='age',
                    columns='gender', aggfunc='mean')
print(p1.round(2))

p2 = pd.pivot_table(d, values='r30', index='age',
                    columns='gender', aggfunc='mean') * 100
print(p2.round(1))

print(pd.crosstab(d['gender'], d['readmitted']))
print(pd.crosstab(df['visit_grp'], df['readmitted'], normalize='index').mul(100).round(1))

"""## 16. Missing-data and category-coding patterns"""

# is <30 readmission different where a value is missing?
for c in ['medical_specialty', 'payer_code', 'race', 'weight']:
    m = df[c].isnull()
    r1 = round(df.loc[m, 'r30'].mean() * 100, 1)
    r2 = round(df.loc[~m, 'r30'].mean() * 100, 1)
    print(c, '| missing rows:', m.sum(), '| <30 rate missing:', r1, '| present:', r2)

print(df['admission_type_id'].value_counts())
print(df['discharge_disposition_id'].value_counts().head(10))

# codes for death / hospice discharge (check IDs_mapping.csv)
end_codes = [11, 13, 14, 19, 20, 21]
e = df['discharge_disposition_id'].isin(end_codes)
print('Death/hospice codes:', e.sum())
print('<30 rate, those:', round(df.loc[e, 'r30'].mean() * 100, 1))
print('<30 rate, others:', round(df.loc[~e, 'r30'].mean() * 100, 1))

"""## 17. Descriptive group-level comparisons"""

# share of encounters readmitted within 30 days (descriptive only)
base = round(df['r30'].mean() * 100, 1)
print('Overall <30 rate (%):', base)

df['inp_grp'] = pd.cut(df['number_inpatient'], bins=[-1, 0, 1, 1000],
                       labels=['0', '1', '2+']).astype(str)

for c in ['age', 'gender', 'visit_grp', 'inp_grp', 'stay_type']:
    t = df.groupby(c)['r30'].agg(['count', 'mean'])
    t['rate_pct'] = (t['mean'] * 100).round(1)
    t['diff_overall'] = (t['rate_pct'] - base).round(1)
    print(t[['count', 'rate_pct', 'diff_overall']])

t = sp.groupby('medical_specialty')['r30'].agg(['count', 'mean'])
t['rate_pct'] = (t['mean'] * 100).round(1)
t['diff_overall'] = (t['rate_pct'] - base).round(1)
print(t[['count', 'rate_pct', 'diff_overall']])

"""## 18. Final findings"""

n = len(df)
pts = df['patient_nbr'].nunique()
multi = round((visits > 1).mean() * 100, 1)
mean_stay = round(df['time_in_hospital'].mean(), 2)
med_stay = df['time_in_hospital'].median()

rp = (df['readmitted'].value_counts() / n * 100).round(1)
r_lt = rp['<30']
r_gt = rp['>30']
r_no = rp['NO']

# age groups with at least 500 encounters
a = df.groupby('age')['r30'].agg(['count', 'mean'])
a = a[a['count'] >= 500]
a_hi = a['mean'].idxmax()
a_lo = a['mean'].idxmin()
a_hi_v = round(a.loc[a_hi, 'mean'] * 100, 1)
a_lo_v = round(a.loc[a_lo, 'mean'] * 100, 1)

gm = d.groupby('gender')['time_in_hospital'].mean().round(2)
g_f = gm['Female']
g_m = gm['Male']
g_word = 'longer' if g_f > g_m else 'shorter'

sm = sp.groupby('medical_specialty')['time_in_hospital'].mean().round(2)
sp_hi = sm.idxmax()
sp_lo = sm.idxmin()
sp_hi_v = sm[sp_hi]
sp_lo_v = sm[sp_lo]

ir = (df.groupby('inp_grp')['r30'].mean() * 100).round(1)
i0 = ir['0']
i2 = ir['2+']

miss_sp = round(df['medical_specialty'].isnull().mean() * 100, 1)

g_diff = round(abs(g_f - g_m), 2)

x = round(df.loc[e, 'r30'].mean() * 100, 1)
y = round(df.loc[~e, 'r30'].mean() * 100, 1)

vr = (df.groupby('visit_grp')['r30'].mean() * 100).round(1)
v1 = vr['1 visit']
v4 = vr['4+ visits']

print(f'1. The data has {n} encounters from {pts} patients. {multi}% of patients have more than one encounter.')
print(f'2. The average stay is {mean_stay} days and the median is {med_stay} days.')
print(f'3. Readmission: within 30 days = {r_lt}%, after 30 days = {r_gt}%, not readmitted = {r_no}%.')
print(f'4. Among age groups with 500+ encounters, the <30 rate is highest for {a_hi} ({a_hi_v}%) and lowest for {a_lo} ({a_lo_v}%).')
print(f'5. Average stay is {g_f} days for females and {g_m} days for males. Females stay {g_word} by {g_diff} days.')
print(f'6. Among the 10 most common specialties, the longest average stay is {sp_hi} ({sp_hi_v} days) and the shortest is {sp_lo} ({sp_lo_v} days).')
print(f'7. The <30 rate is {i0}% with 0 inpatient visits in the previous year and {i2}% with 2 or more.')
print(f'8. {miss_sp}% of medical_specialty values are missing, so specialty results use known values only.')
print(f'9. Encounters with death/hospice discharge codes have a <30 rate of {x}%, compared with {y}% for all other encounters.')
print(f'10. The <30 rate is {v1}% for patients with 1 encounter and {v4}% for patients with 4+ encounters. This is partly because a readmission needs a later encounter in the data.')

